PERSONAS: dict[str, Persona] = {
    p.code: p for p in (TOP_MANAGER, QUALITY_MANAGER, RISK_MANAGER, ANALYST, AUDITOR)
}

# Персона по умолчанию: анонимный/демо-доступ и любая незнакомая роль. Выбран менеджер
# качества — самый предметный «нейтральный» разбор без управленческих сокращений.
DEFAULT_PERSONA_CODE = "QUALITY_MANAGER"

# Роль RBAC → персона. Выводится из поля Persona.roles (единый источник правды: правка
# персоны автоматически меняет маппинг, рассинхрон физически невозможен).
ROLE_TO_PERSONA: dict[str, str] = {
    role: persona.code for persona in PERSONAS.values() for role in persona.roles
}


def resolve(role: str | None) -> Persona:
    """Персона по роли пользователя. Неизвестная/пустая роль → персона по умолчанию."""
    code = ROLE_TO_PERSONA.get((role or "").strip().upper(), DEFAULT_PERSONA_CODE)
    return PERSONAS[code]


def get(code: str | None) -> Persona:
    """Персона по её коду (для API/тестов). Неизвестный код → персона по умолчанию."""
    return PERSONAS.get((code or "").strip().upper(), PERSONAS[DEFAULT_PERSONA_CODE])


def catalog() -> list[dict]:
    """Каталог персон для API/UI (стабильный порядок — как объявлены)."""
    return [p.to_dict() for p in PERSONAS.values()]
