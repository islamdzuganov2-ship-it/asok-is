"""
personas.py — ролевые персоны встроенной LLM (BL-009, ТЗ v18).

Задача: один и тот же конвейер рассуждения должен обращаться к разным адресатам по-разному.
Топ-менеджеру нужен короткий вывод «решение/деньги/срок», менеджеру качества — разбор по
подхарактеристикам ISO 25010, риск-менеджеру — сценарий реализации риска и меры минимизации.

ЕДИНАЯ АРХИТЕКТУРА (ключевой инвариант модуля): системный промпт персоны НЕ пишется с нуля,
а СОБИРАЕТСЯ из общих блоков:

    BASE_IDENTITY (кто) + BASE_HONESTY (правила честности, общие для всех)
                        + persona.role_block (роль и приоритеты адресата)
                        + persona.format_block (формат ответа под адресата)

Отсюда следуют два свойства, которых требовало ТЗ:
  • синхронизация — правила честности (anti-hallucination) физически одни и те же для всех
    персон: их нельзя ослабить в одной роли и забыть в другой;
  • модель-агностичность — промпт не содержит разметки конкретной модели (ChatML/Gemma/Llama);
    разметку накладывает рантайм из шаблона чата GGUF (см. service.complete).

Связь с RBAC: персона выводится из РОЛИ пользователя (ROLE_TO_PERSONA). Каталог ролей —
app.modules.iam.models.User.ALL_ROLES; здесь он НЕ импортируется намеренно (домен llm не
должен зависеть от iam), синхронность стережёт тест test_personas.py.

Персона влияет на: системный промпт, набор ролевых линз конвейера, глубину «почему»,
бюджет токенов и применение чек-листа принципов управления (principles.py).
"""
from __future__ import annotations

from dataclasses import dataclass, field

# ─── Общие блоки промпта (единственный источник правды по честности) ──────────────────

BASE_IDENTITY = (
    "Ты — аналитик качества информационных систем банка. Работаешь по методике МК_8.1 и "
    "стандартам ISO/IEC 25010 (модель качества) и ISO/IEC 38500 (управление ИТ)."
)

# ВНИМАНИЕ: это единственное место, где заданы правила честности. Все персоны их наследуют.
BASE_HONESTY = (
    "СТРОГИЕ ПРАВИЛА (нарушать запрещено):\n"
    "1. Используй ТОЛЬКО факты и числа, явно переданные во входных данных. Не придумывай "
    "метрики, проценты, названия систем, фамилии, суммы и сроки.\n"
    "2. Если данных нет — прямо пиши «данные отсутствуют», не домысливай.\n"
    "3. Не делай прогнозов и оценок, не подкреплённых входными цифрами.\n"
    "4. Числа в ответе должны дословно совпадать с входными.\n"
    "5. Пиши деловым русским языком, по существу, без канцелярских штампов.\n"
    "6. НЕ используй названия управленческих методологий и их иноязычные термины — только "
    "нейтральную аналитическую лексику."
)


@dataclass(frozen=True)
class Persona:
    """Паспорт персоны: кому адресован вывод и как он должен выглядеть."""

    code: str
    title: str                    # человекочитаемое название (UI, отчёты)
    audience: str                 # адресат вывода
    role_block: str               # роль и приоритеты — подставляется в системный промпт
    format_block: str             # требуемый формат ответа
    lens_codes: tuple[str, ...]   # ролевые линзы конвейера (reasoning.REASONING_LENSES)
    why_depth: int = 5            # глубина лестницы «почему» на этапе первопричины
    max_tokens: int = 320         # бюджет ответа (топ-менеджеру нужно короче)
    apply_principles: bool = False  # применять чек-лист принципов управления (principles.py)
    roles: tuple[str, ...] = field(default_factory=tuple)  # роли RBAC, которым назначена персона

    @property
    def system_prompt(self) -> str:
        """Готовый системный промпт персоны (собирается из общих блоков + персональных)."""
        return "\n".join((BASE_IDENTITY, self.role_block, BASE_HONESTY, self.format_block))

    def to_dict(self) -> dict:
        """Паспорт для API/UI (без полного текста промпта — он длинный; см. system_prompt)."""
        return {
            "code": self.code,
            "title": self.title,
            "audience": self.audience,
            "lens_codes": list(self.lens_codes),
            "why_depth": self.why_depth,
            "max_tokens": self.max_tokens,
            "apply_principles": self.apply_principles,
            "roles": list(self.roles),
        }


