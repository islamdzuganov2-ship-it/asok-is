def reasoning_system_prompt(persona: Persona) -> str:
    """Системный промпт конвейера под конкретную персону адресата.

    Собирается из промпта персоны (идентичность + роль + общие правила честности + формат)
    и правил конвейера. Так ролевые контексты синхронизированы по построению: ослабить
    правила честности в одной роли, не тронув остальные, физически невозможно.
    """
    return f"{persona.system_prompt}\n{_REASONING_RULES}"


def checklist_for(persona: Persona) -> str:
    """Чек-лист требований к резюме для персоны (пусто, если персона его не применяет)."""
    return _principles.checklist_block() + "\n" if persona.apply_principles else ""


