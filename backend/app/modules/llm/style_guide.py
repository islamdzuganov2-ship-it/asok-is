"""
style_guide.py — глоссарий делового языка для вывода, адресованного руководителю (BL-009+).

ПРОБЛЕМА (зафиксирована 2026-08-16 по реальному выводу конвейера). Часть текста, который
конвейер (reasoning.py) показывает ЛПР — CEO/CTO/CIO, — была написана словами внутренней
инженерной кухни: «grounding-контроль», «детерминированный fallback», «LLM-вывод
недоступен/отбракован», «движок правил», «трасса», голые коды этапов (E1, E2Q…) и
псевдокод вместо названия правила («[Severity>=High]»). Для читателя, который не занимается
эксплуатацией системы, это не отличимо от отказа системы и подрывает доверие к самому выводу,
а не только к одному разделу отчёта.

ПРИНЦИП ИСПРАВЛЕНИЯ — тот же, что у principles.py с терминологией Toyota:

    механизм (движок правил → LLM → grounding → fallback) ОСТАЁТСЯ как есть в коде и
    в аудируемой трассе для технических персон (менеджер качества, аудитор, тест-аналитик);
    в текст, обращённый к управленческой персоне, слова этой кухни НЕ ПОПАДАЮТ — только
    деловой русский язык результата и причин.

Один глоссарий — два потребителя:
  1. `STYLE_RULE_BLOCK` подмешивается в BASE_HONESTY (personas.py) и тем самым автоматически
     идёт в системный промпт КАЖДОЙ персоны (правила честности — общие для всех, ослабить
     нельзя). Это и есть «обучающий слой», который просили загружать во все прикладываемые LLM:
     он не требует дообучения весов — работает на уровне A (промпт) для любой модели.
  2. `FORBIDDEN_ENGINEERING_TERMS` — тот же список в виде строк для регрессионного теста
     (test_reasoning.py), который проверяет, что жаргон не просочился в детерминированный
     скелет (E4/E6/E7), а не только в LLM-часть.

Формулировки деталей правил (gate.py) и деревьев решений (decisions.py) в этот модуль не
входят намеренно — их правит соответствующий модуль; здесь только реестр запрещённого и
формулировка правила для промпта.
"""
from __future__ import annotations

# Термин инженерной кухни → одобренная деловая формулировка (для человека, правящего строки
# в gate.py/decisions.py/reasoning.py, и как справочник при код-ревью).
JARGON_TO_PLAIN: dict[str, str] = {
    "grounding-контроль": "проверка цифр на достоверность",
    "детерминированный движок правил": "формальные правила методики контроля качества",
    "движок правил": "правила методики контроля качества",
    "детерминированный fallback": "заполнение по формальным правилам (без содержательного анализа)",
    "LLM-вывод недоступен/отбракован": "данных недостаточно для содержательного анализа",
    "аудируемая трасса": "подробный разбор",
    "код этапа (E1, E2Q…)": "название раздела разбора",
    "[Severity>=High]": "человекочитаемое название сработавшего правила",
}

# Подстроки, которых не должно быть в тексте, обращённом к пользователю (регистрозависимо —
# как в проверке терминологии Toyota, principles.py). Корни слов, а не точные фразы: жаргон
# просачивается в разных грамматических формах («детерминированно», «детерминированы»…).
FORBIDDEN_ENGINEERING_TERMS: tuple[str, ...] = (
    "grounding", "Grounding",
    "fallback",
    "LLM-вывод",
    "отбракован",
    "движок",
    "детерминированн",
    "трасс",
)

STYLE_RULE_BLOCK = (
    "7. Пиши так, как будто отвечаешь руководителю, а не описываешь работу самой системы: "
    "не используй слова внутренней инженерной кухни (grounding, fallback, «движок правил», "
    "«детерминированный/детерминированно», «LLM-вывод отбракован», «трасса», голые коды "
    "разделов вроде E1/E2Q). Если раздел не удалось наполнить содержательным анализом — прямо "
    "напиши, каких данных не хватает, а не то, ПОЧЕМУ (по каким внутренним причинам) анализ "
    "не выполнен."
)


def contains_jargon(text: str) -> list[str]:
    """Термины из FORBIDDEN_ENGINEERING_TERMS, найденные в тексте (для тестов/само-проверки)."""
    return [term for term in FORBIDDEN_ENGINEERING_TERMS if term in (text or "")]
