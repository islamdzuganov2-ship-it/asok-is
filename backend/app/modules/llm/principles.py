def checklist_block() -> str:
    """Фрагмент промпта: требования к управленческому резюме (без названий методологий).

    Подмешивается только для персон с apply_principles=True (топ-менеджер), чтобы не раздувать
    промпт там, где адресату нужен предметный разбор, а не управленческая рамка.
    """
    lines = [f"- {p.question}" for p in PRINCIPLES if p.in_prompt]
    return (
        "ОБЯЗАТЕЛЬНЫЕ ТРЕБОВАНИЯ К УПРАВЛЕНЧЕСКОМУ РЕЗЮМЕ (проверь себя по каждому пункту; "
        "если данных для пункта нет — прямо напиши, что данных нет, и не выдумывай):\n"
        + "\n".join(lines)
    )


def _has_marker(text_lower: str, markers: tuple[str, ...]) -> bool:
    return any(m in text_lower for m in markers)


def audit(text: str) -> dict:
    """Признаки отражения принципов в готовом резюме (детерминированно, без LLM).

    Возвращает {"covered": [коды], "missing": [коды], "coverage": доля, "details": [...]}.
    ВАЖНО: это лексический признак присутствия темы в тексте, а не оценка соблюдения принципа
    в реальной работе — формулировка в отчёте должна оставаться именно такой.
    """
    low = (text or "").lower()
    covered: list[str] = []
    missing: list[str] = []
    details: list[dict] = []
    for p in PRINCIPLES:
        hit = _has_marker(low, p.markers)
        (covered if hit else missing).append(p.code)
        details.append({
            "code": p.code, "title": p.title, "reflected": hit, "in_prompt": p.in_prompt,
        })
    total = len(PRINCIPLES)
    return {
        "covered": covered,
        "missing": missing,
        "coverage": round(len(covered) / total, 3) if total else 0.0,
        "details": details,
    }


def prompt_coverage(text: str) -> float:
    """Доля ОБЯЗАТЕЛЬНЫХ (in_prompt) принципов, отражённых в тексте, — ключевой показатель.

    Именно эти пункты явно затребованы промптом, поэтому их отсутствие — дефект резюме,
    а не особенность данных. Используется самооценкой (selfcheck) как проба на полноту.
    """
    low = (text or "").lower()
    required = [p for p in PRINCIPLES if p.in_prompt]
    if not required:
        return 1.0
    hits = sum(1 for p in required if _has_marker(low, p.markers))
    return round(hits / len(required), 3)


def catalog() -> list[dict]:
    """Каталог принципов для API/UI/отчёта (нейтральные формулировки)."""
    return [
        {"code": p.code, "title": p.title, "question": p.question, "in_prompt": p.in_prompt}
        for p in PRINCIPLES
    ]
