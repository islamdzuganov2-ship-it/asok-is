# ─────────────────────────── Доступ к каталогу ───────────────────────────

def entries_for(characteristic: str | None = None,
                subcharacteristic: str | None = None) -> list[CatalogEntry]:
    """Связки каталога с фильтром по характеристике/подхарактеристике."""
    out = MEASURE_CATALOG
    if characteristic:
        out = [e for e in out if e.characteristic == characteristic]
    if subcharacteristic:
        out = [e for e in out if e.subcharacteristic == subcharacteristic]
    return list(out)


def covered_subchars() -> set[tuple[str, str]]:
    """Пары (характеристика, подхарактеристика), покрытые каталогом."""
    return {(e.characteristic, e.subcharacteristic) for e in MEASURE_CATALOG}


def uncovered_subchars() -> set[tuple[str, str]]:
    """Подхарактеристики модели качества БЕЗ типовых мер (инвариант: должно быть пусто)."""
    model = {(c, s) for c, subs in QUALITY_MODEL for s, _f in subs}
    return model - covered_subchars()


# ─────────────────────────── Транспорт (camelCase наружу) ───────────────────────────

class _CamelModel(BaseModel):
    model_config = ConfigDict(alias_generator=to_camel, populate_by_name=True, from_attributes=True)


class CatalogEntryOut(_CamelModel):
    characteristic: str
    subcharacteristic: str
    risk: str
    eliminating: str
    compensating: str


def as_out(entries: list[CatalogEntry]) -> list[CatalogEntryOut]:
    return [CatalogEntryOut.model_validate(e) for e in entries]
