CATALOG: list[CatalogEntry] = [
    CatalogEntry(characteristic=c, subcharacteristic=s, risk=r, eliminating=e, compensating=k)
    for (c, s, r, e, k) in _RAW
]


def catalog_for(characteristic: str | None = None,
                subcharacteristic: str | None = None) -> list[CatalogEntry]:
    """Каталог, отфильтрованный по характеристике и/или подхарактеристике (для подсказок в UI)."""
    out = CATALOG
    if characteristic:
        out = [e for e in out if e.characteristic == characteristic]
    if subcharacteristic:
        out = [e for e in out if e.subcharacteristic == subcharacteristic]
    return out
