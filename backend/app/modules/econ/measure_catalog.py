COMPENSATING = "COMPENSATING"


@dataclass(frozen=True)
class CatalogEntry:
    """Типовая связка: подхарактеристика → риск → пара мер."""
    characteristic: str
    subcharacteristic: str
    risk: str
    eliminating: str      # устраняющая мера (снимает первопричину)
    compensating: str     # компенсирующая (снижает ущерб/вероятность, причина остаётся)


def _e(c: str, s: str, risk: str, elim: str, comp: str) -> CatalogEntry:
    return CatalogEntry(characteristic=c, subcharacteristic=s, risk=risk,
                        eliminating=elim, compensating=comp)


