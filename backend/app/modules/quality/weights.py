# (характеристика, подхарактеристика) → вес подхарактеристики (0..искл., Σ = 100 по всей модели).
SUBCHAR_WEIGHTS: dict[tuple[str, str], float] = {(c, s): w for c, s, w, _iso in _WEIGHT_ROWS}

# (характеристика, подхарактеристика) → английский термин ISO — только для тестов/аудита сшивки.
ISO_KEY_BY_PAIR: dict[tuple[str, str], str] = {(c, s): iso for c, s, _w, iso in _WEIGHT_ROWS}

# характеристика → сумма весов её подхарактеристик (= вес характеристики из файла, проверено
# тестом-стражем на равенство с независимо транскрибированной таблицей).
CHARACTERISTIC_WEIGHTS: dict[str, float] = {}
for _c, _s, _w, _iso in _WEIGHT_ROWS:
    CHARACTERISTIC_WEIGHTS[_c] = CHARACTERISTIC_WEIGHTS.get(_c, 0.0) + _w

TOTAL_WEIGHT: float = sum(SUBCHAR_WEIGHTS.values())  # 100 — контрольная сумма


def subchar_weight(characteristic: str, subcharacteristic: str) -> float:
    """Вес подхарактеристики. KeyError на неизвестной паре — тихий 0 замаскировал бы опечатку
    в имени характеристики/подхарактеристики (та самая ловушка «Доступность» ×2)."""
    return SUBCHAR_WEIGHTS[(characteristic, subcharacteristic)]


# ── ТЗ v19 УК-04 (редактор весов) — разложение плоской таблицы на u×w ──
#
# Файл заказчика даёт ОДНУ плоскую цифру на подхарактеристику, которая уже включает вес своей
# характеристики (см. докстринг модуля). Для независимо редактируемых уровней «u» (вес
# характеристики в интегральном Q ИС) и «w» (вес подхарактеристики ВНУТРИ своей характеристики)
# раскладываем эту цифру лосслесс: u = CHARACTERISTIC_WEIGHTS[char] (уже Σ=100 по 8 характеристикам,
# проверено тестом-стражем), w = 100 × исходный_вес / u(char) (Σ=100 внутри каждой характеристики).
# Обратное произведение u×w/100 даёт исходную плоскую цифру ТОЧНО — редактор ничего не меняет,
# пока администратор явно не сохранит правку (см. weight_editor.py).
#
# «v» (метрика → подхарактеристика) сознательно НЕ вводится как редактируемый уровень: в этой
# модели данных на подхарактеристику всегда ровно ОДНА метрика/формула (QUALITY_MODEL,
# MetricCatalog) — v тождественно равно 1 на каждой строке без единой реальной степени свободы,
# редактируемый UI для него был бы декоративным, а не функциональным.
DEFAULT_CHAR_WEIGHTS: dict[str, float] = dict(CHARACTERISTIC_WEIGHTS)

DEFAULT_SUBCHAR_WITHIN_CHAR: dict[tuple[str, str], float] = {
    (c, s): round(100 * w / CHARACTERISTIC_WEIGHTS[c], 6) for c, s, w, _iso in _WEIGHT_ROWS
}

