def _jitter(key: str) -> float:
    """Детерминированный разброс ±0.035 — чтобы строки не выглядели штампованными."""
    digest = hashlib.sha256(key.encode("utf-8")).digest()
    return (digest[0] / 255.0 - 0.5) * 0.07


def target_x(system_code: str, characteristic: str, sub: str, quarter_idx: int) -> float:
    """Целевое качество подхарактеристики (доля 0..1) для квартала.

    Собирается из сценария системы: база + тренд × номер квартала + сдвиг характеристики +
    разовая аномалия квартала + детерминированный разброс. Результат зажат в 0.02..0.99:
    ноль и единица на демо-данных читаются как ошибка выгрузки, а не как показатель.
    """
    scenario = SCENARIOS.get(system_code)
    if scenario is None:
        scenario = {"base": 0.72, "trend": 0.0, "chars": {}, "anomalies": {}}
    value = scenario["base"] + scenario["trend"] * quarter_idx
    value += scenario["chars"].get(characteristic, 0.0)
    value += scenario["chars"].get(sub, 0.0)
    value += scenario["anomalies"].get((characteristic, QUARTERS[quarter_idx]), 0.0)
    value += _jitter(f"{system_code}|{characteristic}|{sub}|{quarter_idx}")
    return max(0.02, min(0.99, round(value, 4)))
